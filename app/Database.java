/**
 * Lapisan database. Mendukung MySQL/MariaDB (dipakai bersama di jaringan sekolah) dan H2 (lokal).
 * Pengaturan dibaca dari database.properties. Semua perubahan data ditulis ke sini; DataStore
 * memuat ulang isinya dari sini supaya perubahan dari komputer lain ikut terlihat.
 */
final class Database {
    private Database() {
    }

    /** Isi database pada satu saat (foto dimuat terpisah, hanya bila berubah). */
    static final class Snapshot {
        String operatorName;
        BufferedImage operatorPhoto;
        final Map<String, TeacherRecord> teachers = new LinkedHashMap<>();
        final List<StudentRecord> students = new ArrayList<>();
        final List<ScheduleRecord> schedule = new ArrayList<>();
    }

    private static Connection conn;
    private static DbConfig config;

    static DbConfig config() {
        return config;
    }

    // ===================== SAMBUNGAN =====================
    static void open() throws SQLException {
        config = DbConfig.load();
        if (!config.mysql) {
            new File("data").mkdirs();
        }
        conn = connect();
        createSchema();
    }

    private static Connection connect() throws SQLException {
        if (!config.mysql) {
            return DriverManager.getConnection("jdbc:h2:./data/sekolah", "sa", "");
        }
        try {
            return DriverManager.getConnection(config.url(true), config.user, config.password);
        } catch (SQLException e) {
            if (e.getErrorCode() != 1049) { // 1049 = database belum ada
                throw e;
            }
        }
        // Database belum dibuat: buat otomatis (butuh hak CREATE pada user ini).
        try (Connection root = DriverManager.getConnection(config.url(false), config.user, config.password);
             Statement st = root.createStatement()) {
            st.execute("CREATE DATABASE IF NOT EXISTS `" + config.name + "` CHARACTER SET utf8mb4");
        }
        return DriverManager.getConnection(config.url(true), config.user, config.password);
    }

    /** Sambungan aktif; bila terputus (mis. server memutus koneksi lama) disambung ulang otomatis. */
    private static Connection connection() throws SQLException {
        if (conn == null || conn.isClosed() || !conn.isValid(2)) {
            try {
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException ignored) {
                // abaikan
            }
            conn = connect();
        }
        return conn;
    }

    private static void createSchema() throws SQLException {
        boolean my = config.mysql;
        String blob = my ? "LONGBLOB" : "BLOB";
        String seq = my ? "seq BIGINT AUTO_INCREMENT UNIQUE" : "seq BIGINT GENERATED BY DEFAULT AS IDENTITY";
        String id = my ? "id BIGINT AUTO_INCREMENT PRIMARY KEY" : "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
        String tail = my ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4" : "";
        try (Statement st = connection().createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS operator_profile ("
                + "id INT PRIMARY KEY, name VARCHAR(200), photo " + blob + ")" + tail);
            st.execute("CREATE TABLE IF NOT EXISTS teachers ("
                + "username VARCHAR(200) PRIMARY KEY, name VARCHAR(200) NOT NULL, "
                + "password VARCHAR(200) NOT NULL, subjects VARCHAR(4000), photo " + blob + ", "
                + "photo_stamp BIGINT DEFAULT 0, " + seq + ")" + tail);
            st.execute("CREATE TABLE IF NOT EXISTS students ("
                + "username VARCHAR(200) PRIMARY KEY, name VARCHAR(200) NOT NULL, "
                + "student_class VARCHAR(10) NOT NULL, address VARCHAR(500), email VARCHAR(200), "
                + "phone VARCHAR(50), password VARCHAR(200) NOT NULL, photo " + blob + ", "
                + "photo_stamp BIGINT DEFAULT 0, " + seq + ")" + tail);
            st.execute("CREATE TABLE IF NOT EXISTS grades ("
                + "username VARCHAR(200) NOT NULL, subject VARCHAR(200) NOT NULL, score DOUBLE NOT NULL, "
                + "PRIMARY KEY (username, subject))" + tail);
            st.execute("CREATE TABLE IF NOT EXISTS schedule ("
                + id + ", day_name VARCHAR(20) NOT NULL, "
                + "start_min INT NOT NULL, end_min INT NOT NULL, student_class VARCHAR(10) NOT NULL, "
                + "subject VARCHAR(200) NOT NULL, teacher VARCHAR(200))" + tail);
        }
        // Database lama (versi sebelumnya) belum punya kolom photo_stamp: tambahkan.
        for (String table : new String[]{"teachers", "students"}) {
            if (!hasColumn(table, "photo_stamp")) {
                try (Statement st = connection().createStatement()) {
                    st.execute("ALTER TABLE " + table + " ADD COLUMN photo_stamp BIGINT DEFAULT 0");
                }
            }
        }
    }

    private static boolean hasColumn(String table, String column) throws SQLException {
        DatabaseMetaData md = connection().getMetaData();
        for (String t : new String[]{table, table.toUpperCase()}) {
            try (ResultSet rs = md.getColumns(null, null, t, column)) {
                if (rs.next()) {
                    return true;
                }
            }
            try (ResultSet rs = md.getColumns(null, null, t, column.toUpperCase())) {
                if (rs.next()) {
                    return true;
                }
            }
        }
        return false;
    }

    // ===================== MUAT DATA =====================
    static Snapshot loadSnapshot() throws SQLException {
        Snapshot snap = new Snapshot();
        Map<String, StudentRecord> byUser = new LinkedHashMap<>();
        try (Statement st = connection().createStatement()) {
            try (ResultSet rs = st.executeQuery("SELECT name, photo FROM operator_profile WHERE id = 1")) {
                if (rs.next()) {
                    snap.operatorName = rs.getString(1);
                    snap.operatorPhoto = toImage(rs.getBytes(2));
                }
            }
            try (ResultSet rs = st.executeQuery(
                "SELECT username, name, password, subjects, photo_stamp FROM teachers ORDER BY seq")) {
                while (rs.next()) {
                    TeacherRecord t = new TeacherRecord(rs.getString(2), rs.getString(1), rs.getString(3));
                    String subjects = rs.getString(4);
                    if (subjects != null && !subjects.isEmpty()) {
                        for (String s : subjects.split("\n")) {
                            if (!s.trim().isEmpty()) {
                                t.subjects.add(s.trim());
                            }
                        }
                    }
                    t.photoStamp = rs.getLong(5);
                    snap.teachers.put(t.username, t);
                }
            }
            try (ResultSet rs = st.executeQuery(
                "SELECT name, student_class, address, email, phone, username, password, photo_stamp "
                    + "FROM students ORDER BY seq")) {
                while (rs.next()) {
                    StudentRecord s = new StudentRecord(rs.getString(1), rs.getString(2),
                        nz(rs.getString(3)), nz(rs.getString(4)), nz(rs.getString(5)),
                        rs.getString(6), rs.getString(7));
                    s.photoStamp = rs.getLong(8);
                    snap.students.add(s);
                    byUser.put(s.username, s);
                }
            }
            try (ResultSet rs = st.executeQuery("SELECT username, subject, score FROM grades ORDER BY subject")) {
                while (rs.next()) {
                    StudentRecord s = byUser.get(rs.getString(1));
                    if (s != null) {
                        s.grades.add(new GradeRecord(rs.getString(2), rs.getDouble(3)));
                    }
                }
            }
            try (ResultSet rs = st.executeQuery(
                "SELECT id, day_name, start_min, end_min, student_class, subject, teacher FROM schedule ORDER BY id")) {
                while (rs.next()) {
                    ScheduleRecord r = new ScheduleRecord(rs.getString(2), rs.getInt(3), rs.getInt(4),
                        rs.getString(5), rs.getString(6), rs.getString(7));
                    r.id = rs.getLong(1);
                    snap.schedule.add(r);
                }
            }
        }
        return snap;
    }

    static BufferedImage loadTeacherPhoto(String username) throws SQLException {
        return loadPhoto("SELECT photo FROM teachers WHERE username = ?", username);
    }

    static BufferedImage loadStudentPhoto(String username) throws SQLException {
        return loadPhoto("SELECT photo FROM students WHERE username = ?", username);
    }

    private static BufferedImage loadPhoto(String sql, String username) throws SQLException {
        try (PreparedStatement ps = connection().prepareStatement(sql)) {
            ps.setString(1, username);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? toImage(rs.getBytes(1)) : null;
            }
        }
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }

    // ===================== OPERATOR =====================
    static void saveOperator(String name, BufferedImage photo) throws SQLException {
        int n = update("UPDATE operator_profile SET name = ?, photo = ? WHERE id = 1", name, bytes(photo));
        if (n == 0) {
            update("INSERT INTO operator_profile (id, name, photo) VALUES (1, ?, ?)", name, bytes(photo));
        }
    }

    // ===================== GURU =====================
    static void saveTeacher(TeacherRecord t) throws SQLException {
        String subjects = String.join("\n", t.subjects);
        t.photoStamp = t.photo == null ? 0 : System.currentTimeMillis();
        int n = update("UPDATE teachers SET name = ?, password = ?, subjects = ?, photo = ?, photo_stamp = ? "
                + "WHERE username = ?",
            t.name, t.password, subjects, bytes(t.photo), t.photoStamp, t.username);
        if (n == 0) {
            update("INSERT INTO teachers (username, name, password, subjects, photo, photo_stamp) "
                    + "VALUES (?, ?, ?, ?, ?, ?)",
                t.username, t.name, t.password, subjects, bytes(t.photo), t.photoStamp);
        }
    }

    static void deleteTeacher(String username) throws SQLException {
        update("UPDATE schedule SET teacher = NULL WHERE teacher = ?", username);
        update("DELETE FROM teachers WHERE username = ?", username);
    }

    // ===================== SISWA =====================
    static void saveStudent(StudentRecord s) throws SQLException {
        s.photoStamp = s.photo == null ? 0 : System.currentTimeMillis();
        int n = update("UPDATE students SET name = ?, student_class = ?, address = ?, email = ?, phone = ?, "
                + "password = ?, photo = ?, photo_stamp = ? WHERE username = ?",
            s.name, s.studentClass, s.address, s.email, s.phone, s.password, bytes(s.photo), s.photoStamp,
            s.username);
        if (n == 0) {
            update("INSERT INTO students (name, student_class, address, email, phone, password, photo, "
                    + "photo_stamp, username) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                s.name, s.studentClass, s.address, s.email, s.phone, s.password, bytes(s.photo), s.photoStamp,
                s.username);
        }
    }

    static void deleteStudent(String username) throws SQLException {
        update("DELETE FROM grades WHERE username = ?", username);
        update("DELETE FROM students WHERE username = ?", username);
    }

    static void saveGrade(String username, String subject, double score) throws SQLException {
        int n = update("UPDATE grades SET score = ? WHERE username = ? AND LOWER(subject) = LOWER(?)",
            score, username, subject);
        if (n == 0) {
            update("INSERT INTO grades (username, subject, score) VALUES (?, ?, ?)", username, subject, score);
        }
    }

    // ===================== JADWAL =====================
    static long saveSchedule(ScheduleRecord r) throws SQLException {
        if (r.id > 0) {
            update("UPDATE schedule SET day_name = ?, start_min = ?, end_min = ?, student_class = ?, subject = ?, "
                    + "teacher = ? WHERE id = ?",
                r.day, r.startMinute, r.endMinute, r.studentClass, r.subject, r.teacherUsername, r.id);
            return r.id;
        }
        try (PreparedStatement ps = connection().prepareStatement(
            "INSERT INTO schedule (day_name, start_min, end_min, student_class, subject, teacher) "
                + "VALUES (?, ?, ?, ?, ?, ?)", Statement.RETURN_GENERATED_KEYS)) {
            bind(ps, r.day, r.startMinute, r.endMinute, r.studentClass, r.subject, r.teacherUsername);
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getLong(1);
                }
            }
        }
        return 0;
    }

    static void deleteSchedule(long id) throws SQLException {
        update("DELETE FROM schedule WHERE id = ?", id);
    }

    // ===================== BANTUAN JDBC =====================
    private static int update(String sql, Object... params) throws SQLException {
        try (PreparedStatement ps = connection().prepareStatement(sql)) {
            bind(ps, params);
            return ps.executeUpdate();
        }
    }

    private static void bind(PreparedStatement ps, Object... params) throws SQLException {
        for (int i = 0; i < params.length; i++) {
            Object v = params[i];
            if (v == null) {
                ps.setNull(i + 1, Types.NULL);
            } else if (v instanceof byte[]) {
                ps.setBytes(i + 1, (byte[]) v);
            } else {
                ps.setObject(i + 1, v);
            }
        }
    }

    private static byte[] bytes(BufferedImage img) {
        if (img == null) {
            return null;
        }
        try {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(img, "png", out);
            return out.toByteArray();
        } catch (Exception e) {
            return null;
        }
    }

    private static BufferedImage toImage(byte[] data) {
        if (data == null || data.length == 0) {
            return null;
        }
        try {
            return ImageIO.read(new ByteArrayInputStream(data));
        } catch (Exception e) {
            return null;
        }
    }
}
